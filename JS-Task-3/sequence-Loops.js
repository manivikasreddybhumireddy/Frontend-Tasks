// 1. Print numbers from 1 lakh to 2 lakh
for (let i = 100000; i <= 200000; i++) {
    console.log(i);
}


// 2. Print: 1 4 9 16 25 ... 100
for (let i = 1; i <= 10; i++) {
    console.log(i * i);
}


// 3. Print: 1 8 27 64 125 ... 1000
for (let i = 1; i <= 10; i++) {
    console.log(i * i * i);
}


// 4.Print numbers from 5 lakh to 4 lakh in reverse order
for (let i = 500000; i >= 400000; i--) {
    console.log(i);
}


// 5. Print: 2.5 2 1.5 1 0.5
for (let i = 2.5; i >= 0.5; i = i - 0.5) {
    console.log(i);
}
